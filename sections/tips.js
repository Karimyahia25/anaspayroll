// أسبوع من أول 1970 — النصيحة بتتغيّر كل أسبوع
const weekNo = () => Math.floor((Date.now() + 2 * 3600e3) / (7 * 864e5));

// kinds: 'd' عميل حفاضات · 'm' عميل لبن. الحفاضات ← نصايح الحفاضات + الطفل · اللبن ← الطفل + الأم · الاتنين ← الكل.
export function pickTip(custId, kinds) {
  const k = String(kinds || ''), d = k.includes('d'), m = k.includes('m');
  const pool = d && m ? [...TIPS.diaper, ...TIPS.baby, ...TIPS.mom] : d ? [...TIPS.diaper, ...TIPS.baby] : [...TIPS.baby, ...TIPS.mom];
  return pool[(Math.abs(+custId || 0) * 31 + weekNo()) % pool.length];
}
